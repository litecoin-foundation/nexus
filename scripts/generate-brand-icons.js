#!/usr/bin/env node
// Regenerates the brand icon registry in src/assets/brand-icons from the
// images in that folder; run `npm run brand-icons` after adding or removing
// an icon. Name each file after the brand's slug:
//   raster: playstation.png, with optional @2x / @3x variants (png, jpg, webp)
//   vector: playstation.svg
// Other slugs that should share an icon are mapped by hand in aliases.ts.
//
// Metro can only bundle images named in static require() calls, so raster
// icons are listed as requires in index.ts. SVG icons are inlined as markup
// in svgs.ts instead: both Skia and react-native-svg draw from the string,
// the same way on every platform, with no asset loading at runtime.

const fs = require('fs');
const path = require('path');

const DIR = path.join(__dirname, '..', 'src', 'assets', 'brand-icons');
const INDEX = path.join(DIR, 'index.ts');
const SVGS = path.join(DIR, 'svgs.ts');
const RASTER = /^(.+?)(@[23]x)?\.(png|jpe?g|webp)$/i;
const SVG = /^(.+)\.svg$/i;

const fail = message => {
  console.error(`brand-icons: ${message}`);
  process.exit(1);
};

const normalizeSvg = (name, markup) => {
  let svg = markup
    .replace(/<\?xml[\s\S]*?\?>/g, '')
    .replace(/<!DOCTYPE[\s\S]*?>/gi, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  const root = /<svg\b[^>]*>/i.exec(svg);
  if (!root) {
    fail(`${name}.svg has no <svg> element`);
  }
  if (!/\sviewBox\s*=/i.test(root[0])) {
    const size = attr =>
      new RegExp(`\\s${attr}\\s*=\\s*["']\\s*([\\d.]+)(px)?\\s*["']`, 'i').exec(
        root[0],
      )?.[1];
    const width = size('width');
    const height = size('height');
    if (!width || !height) {
      fail(`${name}.svg needs a viewBox (or a numeric width and height)`);
    }
    svg = svg.replace(/<svg\b/i, `<svg viewBox="0 0 ${width} ${height}"`);
  }
  return svg;
};

const raster = new Map();
const svgs = new Map();
for (const file of fs.readdirSync(DIR)) {
  const svgMatch = SVG.exec(file);
  if (svgMatch) {
    const name = svgMatch[1];
    svgs.set(
      name,
      normalizeSvg(name, fs.readFileSync(path.join(DIR, file), 'utf8')),
    );
    continue;
  }
  const match = RASTER.exec(file);
  if (!match) {
    continue;
  }
  const [, name, , ext] = match;
  // Metro resolves the @2x / @3x variants from the base name
  const base = `./${name}.${ext}`;
  const existing = raster.get(name);
  if (existing && existing !== base) {
    fail(`"${name}" has more than one image format`);
  }
  raster.set(name, base);
}
for (const name of svgs.keys()) {
  if (raster.has(name)) {
    fail(`"${name}" has both an svg and a raster image`);
  }
}

const header = [
  '// Generated by scripts/generate-brand-icons.js; do not edit by hand.',
  '// Run `npm run brand-icons` after adding or removing an icon here.',
];
const sorted = map => [...map.keys()].sort();

const indexSource = [
  ...header,
  "// Keys are brand slugs; a bundled icon replaces the brand's remote logo.",
  '// Slugs that share an icon (one brand, per-country slugs) go in aliases.ts.',
  '',
  "import {BRAND_ICON_SVGS} from './svgs';",
  '',
  '// raster icons, as bundled assets',
  'export const BRAND_ICONS = {',
  ...sorted(raster).map(
    name =>
      `  ${JSON.stringify(name)}: require(${JSON.stringify(raster.get(name))}),`,
  ),
  '} satisfies Record<string, number>;',
  '',
  'export {BRAND_ICON_SVGS};',
  '',
  '// the icon names, so aliases.ts can only point at icons that exist',
  'export type BrandIconName =',
  '  | keyof typeof BRAND_ICONS',
  '  | keyof typeof BRAND_ICON_SVGS;',
  '',
].join('\n');

const svgsSource = [
  ...header,
  '// The SVG icons, inlined as markup; keys are brand slugs.',
  '',
  'export const BRAND_ICON_SVGS = {',
  ...sorted(svgs).map(
    name => `  ${JSON.stringify(name)}: ${JSON.stringify(svgs.get(name))},`,
  ),
  '} satisfies Record<string, string>;',
  '',
].join('\n');

const main = async () => {
  const prettier = require('prettier');
  const write = async (file, source) => {
    const options = (await prettier.resolveConfig(file)) ?? {};
    fs.writeFileSync(
      file,
      await prettier.format(source, {...options, filepath: file}),
    );
  };
  await write(INDEX, indexSource);
  await write(SVGS, svgsSource);
  console.log(
    `brand-icons: ${raster.size} raster, ${svgs.size} svg -> ${path.relative(process.cwd(), DIR)}`,
  );
};

main().catch(error => {
  console.error(error);
  process.exit(1);
});
